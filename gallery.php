document.addEventListener("DOMContentLoaded", function () {

    const galleryItems = document.querySelectorAll(".open-gallery");
    const galleryModal = new bootstrap.Modal(document.getElementById("galleryModal"));

    const image = document.getElementById("galleryImage");
    const video = document.getElementById("galleryVideo");
    const videoSource = document.getElementById("galleryVideoSource");
    const title = document.getElementById("galleryTitle");

    let currentIndex = 0;

    function showItem(index) {

        currentIndex = index;

        // Stop previous video
        video.pause();
        video.currentTime = 0;
        video.style.display = "none";
        videoSource.src = "";

        image.style.display = "none";

        const item = galleryItems[index];

        title.innerHTML = item.dataset.title;

        if (item.dataset.type === "video") {

            video.style.display = "block";
            videoSource.src = item.dataset.video;
            video.load();
            video.play();

        } else {

            image.style.display = "block";
            image.src = item.dataset.image;

        }
    }

    // Open Gallery
    galleryItems.forEach(function (item, index) {

        item.addEventListener("click", function () {

            showItem(index);
            galleryModal.show();

        });

    });

    // Next Button
    document.getElementById("nextBtn").addEventListener("click", function () {

        currentIndex++;

        if (currentIndex >= galleryItems.length) {
            currentIndex = 0;
        }

        showItem(currentIndex);

    });

    // Previous Button
    document.getElementById("prevBtn").addEventListener("click", function () {

        currentIndex--;

        if (currentIndex < 0) {
            currentIndex = galleryItems.length - 1;
        }

        showItem(currentIndex);

    });

    // Keyboard Navigation
    document.addEventListener("keydown", function (e) {

        if (!document.getElementById("galleryModal").classList.contains("show"))
            return;

        if (e.key === "ArrowRight") {
            document.getElementById("nextBtn").click();
        }

        if (e.key === "ArrowLeft") {
            document.getElementById("prevBtn").click();
        }

    });

    // Stop video when modal closes
    document.getElementById("galleryModal").addEventListener("hidden.bs.modal", function () {

        video.pause();
        video.currentTime = 0;
        videoSource.src = "";
        video.load();

    });

});
</script>

